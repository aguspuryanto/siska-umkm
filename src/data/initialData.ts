// Helper to generate past dates
const now = new Date();
const getPastDate = (daysAgo: number, hours = 10, minutes = 15) => {
  const d = new Date(now);
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hours, minutes, 0, 0);
  return d.toISOString();
};

